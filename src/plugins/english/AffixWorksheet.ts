// Affixes — SEVEN procedural kinds (upper primary) extended by THREE
// level-gated root kinds (T5, Year 5+):
//   0. written: "what does the prefix/suffix mean in '<word>'?" (gloss)
//   1. MC: which word contains the dealt prefix/suffix (3 options)
//   2. written: "add the prefix/suffix to '<base>'" (spelling answer)
//   3. MC: what does the dealt affix do (3 gloss options)
//   4. written: "split '<whole>' into affix + base" (reverse of adding)
//   5. MC APPLY: which bank word fits the curated sentence frame
//   6. open-ended COMPOSE: "write a word with the prefix/suffix X" — the key
//      gives one bank example and accepts any sensible word
//   7. (caps.level >= 5) ROOT MEANING MC: "what does the root X mean in W?"
//   8. (caps.level >= 5) ROOT COMPOSE: "write a word that uses the root X"
//      (example + acceptance note)
//   9. (caps.level === 6) ROOT SPOT MC: "which word uses the root X?"
//
// NON-REPEATING SAMPLING: items are dealt from decks and every question
// passes through sampleUnique keyed on the printed prompt. The root decks
// are created ONLY for levels that draw them, so the Year-3/Year-4 rng
// streams (and their pins) are byte-identical to the pre-T5 generator.
function generateAffix(rng: Rng, caps: Caps, count: number): RawProblem[] {
    const prefixDeck = localDeck(rng, PREFIX_ITEMS);
    const suffixDeck = localDeck(rng, SUFFIX_ITEMS);
    const sentenceDeck = localDeck(rng, AFFIX_SENTENCES);
    // T5: explicit level branching via caps.level (never wordTier inference).
    const maxKind = caps.level >= 6 ? 9 : caps.level >= 5 ? 8 : 6;
    const rootDeck = caps.level >= 5 ? localDeck(rng, ROOT_ITEMS) : null;
    // MC kind 3 glosses drawn from the item's own bank (same affix position).
    return sampleUnique(
        count,
        () => {
            const kind = rng.int(0, maxKind);
            if (kind === 7 && rootDeck) {
                // ROOT MEANING (Y5+): the root's meaning beside two meanings
                // from OTHER roots (all distinct glosses in this bank).
                const [root, meaning, example] = rootDeck.take();
                const others = ROOT_ITEMS.filter((i) => i[1] !== meaning);
                const o1 = rng.pick(others)[1];
                let o2 = rng.pick(others)[1];
                if (o2 === o1) o2 = others[(others.findIndex((i) => i[1] === o1) + 1) % others.length][1];
                const shown = shuffleLocal(rng, [meaning, o1, o2]);
                return {
                    prompt: `What does the root "${root}" mean in "${example}"? (${shown.join(', ')})`,
                    answer: meaning
                };
            }
            if (kind === 8 && rootDeck) {
                // ROOT COMPOSE (Y5+): open production from the root.
                const [root, meaning, example] = rootDeck.take();
                return {
                    prompt: `Write a word that uses the root "${root}" (meaning "${meaning}").`,
                    answer: `Example: ${example} (any real word using the root "${root}" is correct)`
                };
            }
            if (kind === 9 && rootDeck) {
                // ROOT SPOT (Y6): which word contains the root — distractors
                // are other roots' example words (no substring collision:
                // every root here is unique across the bank).
                const [root, meaning, example] = rootDeck.take();
                const others = ROOT_ITEMS.filter((i) => i[0] !== root && !i[2].includes(root));
                const o1 = rng.pick(others)[2];
                let o2 = rng.pick(others)[2];
                if (o2 === o1) o2 = others[(others.findIndex((i) => i[2] === o1) + 1) % others.length][2];
                const shown = shuffleLocal(rng, [example, o1, o2]);
                return {
                    prompt: `Which word uses the root "${root}" (meaning "${meaning}")? (${shown.join(', ')})`,
                    answer: example
                };
            }
            if (kind === 5) {
                // APPLY: the one bank word that fits the sentence frame,
                // beside two frame-specific distractors.
                const [answer, sentence, distractors] = sentenceDeck.take();
                const shown = shuffleLocal(rng, [answer, ...distractors]);
                return { prompt: `Which word fits: ${sentence} (${shown.join(', ')})`, answer };
            }
            if (kind === 6) {
                // OPEN-ENDED compose: any real word carrying the affix is
                // correct; the example comes from the bank. NOTE the tuple
                // layouts: the affix sits at index 0 for prefixes but index 1
                // for suffixes ([base, suffix, whole, meaning]).
                const usePrefix = rng.next() < 0.5;
                const bank = usePrefix ? PREFIX_ITEMS : SUFFIX_ITEMS;
                const affixIdx = usePrefix ? 0 : 1;
                const affix = rng.pick(bank)[affixIdx];
                const matches = bank.filter((i) => i[affixIdx] === affix);
                const example = matches[rng.int(0, matches.length - 1)][2];
                return {
                    prompt: `Write a word that has the ${usePrefix ? 'prefix' : 'suffix'} "${affix}".`,
                    answer: `Example: ${example} (any real word with the ${usePrefix ? 'prefix' : 'suffix'} "${affix}" is correct)`
                };
            }
            const usePrefix = rng.next() < 0.5;
            const item = usePrefix ? prefixDeck.take() : suffixDeck.take();
            // Tuple layouts differ: PREFIX_ITEMS are [affix, base, whole,
            // meaning] while SUFFIX_ITEMS read [base, suffix, whole, meaning]
            // — normalise so `affix` always leads and `base` is the word the
            // affix attaches to (without this, a suffix prompt would print
            // the BASE word, e.g. "the suffix 'teach'").
            const [affix, base, whole, meaning] = usePrefix
                ? item
                : ([item[1], item[0], item[2], item[3]] as [string, string, string, string]);
            if (kind === 0) {
                return {
                    prompt: `What does the ${usePrefix ? 'prefix' : 'suffix'} "${affix}" mean in "${whole}"?`,
                    answer: meaning
                };
            }
            if (kind === 1) {
                // MC: which word contains the affix. Distractors are whole
                // words from the opposite bank (no shared affix).
                const distractorBank = usePrefix ? SUFFIX_ITEMS : PREFIX_ITEMS;
                const options = [whole];
                let guard = 0;
                while (options.length < 3 && guard < 24) {
                    guard++;
                    const pick = rng.pick(distractorBank)[2];
                    if (!pick.includes(affix) && !options.includes(pick)) options.push(pick);
                }
                const shown = shuffleLocal(rng, options);
                return {
                    prompt: `Which word has the ${usePrefix ? 'prefix' : 'suffix'} "${affix}"? (${shown.join(', ')})`,
                    answer: whole
                };
            }
            if (kind === 2) {
                return {
                    prompt: `Add the ${usePrefix ? 'prefix' : 'suffix'} "${affix}" to "${base}".`,
                    answer: whole
                };
            }
            if (kind === 4) {
                // SPLIT: reverse of adding — the child separates the morphemes.
                const parts = usePrefix ? `${affix} + ${base}` : `${base} + ${affix}`;
                return {
                    prompt: `Split "${whole}" into its ${usePrefix ? 'prefix' : 'suffix'} and base word.`,
                    answer: parts
                };
            }
            // MC gloss: the right meaning beside two glosses from other items.
            const glossBank = usePrefix ? PREFIX_ITEMS : SUFFIX_ITEMS;
            const options = [meaning];
            let guard = 0;
            while (options.length < 3 && guard < 24) {
                guard++;
                const pick = rng.pick(glossBank)[3];
                if (pick !== meaning && !options.includes(pick)) options.push(pick);
            }
            const shown = shuffleLocal(rng, options);
            return {
                prompt: `What does the ${usePrefix ? 'prefix' : 'suffix'} "${affix}" do? (${shown.join(', ')})`,
                answer: meaning
            };
        },
        (p) => p.prompt
    );
}

// Local Fisher–Yates shuffle (plugin isolation: no cross-plugin imports).
function shuffleLocal<T>(rng: Rng, items: readonly T[]): T[] {
    const out = [...items];
    for (let i = out.length - 1; i > 0; i--) {
        const j = rng.int(0, i);
        [out[i], out[j]] = [out[j], out[i]];
    }
    return out;
}

// Local deck (same contract as the framework's createDeck, kept local so the
// plugin file stays self-contained per the plugin contract in types.ts).
function localDeck<T>(rng: Rng, pool: readonly T[]): { take: () => T } {
    let queue = shuffleLocal(rng, pool);
    return {
        take: () => {
            if (queue.length === 0) queue = shuffleLocal(rng, pool);
            return queue.pop() as T;
        }
    };
}

// The plugin's declarative spec (exported for its own tests). T4C: 8 roomy
