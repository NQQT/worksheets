// Explicit year-level routing via caps.level (T5) — clamp defensively.
const BANKS: Record<3 | 4 | 5 | 6, readonly EditItem[]> = { 3: ITEMS_Y3, 4: ITEMS_Y4, 5: ITEMS_Y5, 6: ITEMS_Y6 };
const IMPROVE: Record<number, readonly [string, string, string][]> = { 5: IMPROVE_Y5, 6: IMPROVE_Y6 };

// Generator — kinds 0–2 every year, kind 3 (IMPROVE) from Year 5:
function generateEditing(rng: Rng, caps: Caps, count: number): RawProblem[] {
    const level = Math.min(Math.max(caps.level, 3), 6) as 3 | 4 | 5 | 6;
    const bank = BANKS[level];
    const deck = localDeck(rng, bank);
    // T9: CHOOSE is restricted to CLOSED (single-correct) items — an "open"
    // item's correction is a style rewording, so its buggy twin is merely
    // informal/biased, not wrong, and "Which sentence is correct?" would
    // have several defensible answers. Open items stay in FIX (with
    // Example guidance) and IMPROVE.
    const closed = bank.filter((i) => !i.open);
    const closedDeck = localDeck(rng, closed);
    const maxKind = level >= 5 ? 3 : 2;
    return sampleUnique(
        count,
        () => {
            const kind = rng.int(0, maxKind);
            if (kind === 3) {
                // STRETCH improve: open rewording with model + acceptance.
                const [instruction, source, model] = rng.pick(IMPROVE[level]);
                return { prompt: `${instruction}\n"${source}"\n${RULE}`, answer: model };
            }
            if (kind === 2) {
                // CHOOSE: the one correct sentence among the dealt closed
                // item's correction and two buggy twins from OTHER closed
                // items (options joined " / " — sentences contain commas).
                const item = closedDeck.take();
                const distractors = closed.filter((i) => i.buggy !== item.buggy);
                const d1 = rng.pick(distractors);
                let d2 = rng.pick(distractors);
                if (d2.buggy === d1.buggy) d2 = distractors[(distractors.indexOf(d1) + 1) % distractors.length];
                const shown = shuffleLocal(rng, [item.correct, d1.buggy, d2.buggy]);
                return { prompt: `Which sentence is correct? (${shown.join(' / ')})`, answer: item.correct };
            }
            const item = deck.take();
            if (kind === 0) {
                // FIX: rewrite the sentence. Open items (rewordings) print
                // their model + acceptance note; deterministic fixes print
                // the exact corrected sentence.
                const answer = item.open
                    ? `Example: ${item.correct} (any sensible corrected sentence is accepted)`
                    : item.correct;
                return { prompt: `Correct this sentence:\n"${item.buggy}"\n${RULE}`, answer };
            }
            // SPOT: name the error kind (category + two other categories).
            // Every bank sentence carries exactly ONE error category, so the
            // named kind is never ambiguous.
            const others = CATEGORIES.filter((c) => c !== item.category);
            const o1 = rng.pick(others);
            let o2 = rng.pick(others);
            if (o2 === o1) o2 = others[(others.indexOf(o1) + 1) % others.length];
            const shown = shuffleLocal(rng, [item.category, o1, o2]);
            return { prompt: `What kind of mistake is in this sentence?\n"${item.buggy}" (${shown.join(', ')})`, answer: item.category };
        },
        (p) => p.prompt
    );
}

// Local Fisher–Yates shuffle (plugin isolation: no cross-plugin imports).
function shuffleLocal<T>(rng: Rng, items: readonly T[]): T[] {
    const out = [...items];
    for (let i = out.length - 1; i > 0; i--) {
        const j = rng.int(0, i);
        [out[i], out[j]] = [out[j], out[i]];
    }
    return out;
}

// Local deck (same contract as the framework's createDeck, kept local so the
// plugin file stays self-contained per the plugin contract in types.ts).
function localDeck<T>(rng: Rng, pool: readonly T[]): { take: () => T } {
    let queue = shuffleLocal(rng, pool);
    return {
        take: () => {
            if (queue.length === 0) queue = shuffleLocal(rng, pool);
            return queue.pop() as T;
        }
    };
}

// Per-year scope line — exposes the editing-focus progression.
const SCOPE_BY_LEVEL: Record<number, string> = {
    3: 'capital letters and end punctuation',
    4: 'speech marks, spelling and commonly confused words',
    5: 'commas and subject–verb agreement',
    6: 'formality, precision and bias'
};

// The plugin's declarative spec (exported for its own tests). Prose rows —
// single column, 5 rows per A4 page (buggy sentence + rewrite line). T12:
// 6 rows exceeded the 915px printable grid budget on keyed pages (analytical
// model: 45 chars/line, 30px prompt line, 18.2px answer line); 5 rows keeps
// every grade inside the budget with the key ON.
export const editingSpec: WorksheetSpec = {
    id: 'editing',
    label: 'Editing & Proofreading',
    icon: '✓',
    perPage: 5,
    singleColumn: true,
    offered: (grade: GradeConfig) => grade.available.includes('editing'),
    scope: (grade: GradeConfig) => SCOPE_BY_LEVEL[grade.caps.level] ?? SCOPE_BY_LEVEL[3],
    generate: generateEditing
};

// The plugin: a function the dashboard calls with its framework bundle.
export function EditingWorksheet(dashboard: DashboardFramework): DashboardPlugin {
    return dashboard.createWorksheet(editingSpec);
}
