// One comprehension question. `kind` documents the scaffold step for the
// next agent: literal = find, infer = read between the lines, evidence =
// quote/judge. `a` is the model answer; for infer questions the generator
// appends the acceptance note.
type CompQuestion = { q: string; a: string; kind: 'literal' | 'infer' | 'evidence' };

// A passage block: title + text + its three scaffolded questions. The whole
// block prints as ONE problem row so the passage never separates from (or
// repeats for) its questions.
type Passage = { title: string; text: string; questions: [CompQuestion, CompQuestion, CompQuestion] };

// A ruled WRITING line: ten "__" tokens render as ten connected fill-in
// blanks on one baseline (PrintableSheet PromptText splits prompts on "__").
