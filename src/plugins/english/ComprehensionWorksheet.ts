// Explicit year-level routing (T5): the caps.level knob selects the bank —
// no fragile wordTier/sentenceLen inference. Unknown levels clamp to Y3 so a
// misconfigured grade can never crash the generator.
const BANKS: Record<3 | 4 | 5 | 6, readonly Passage[]> = { 3: PASSAGES_Y3, 4: PASSAGES_Y4, 5: PASSAGES_Y5, 6: PASSAGES_Y6 };

// Render one passage as a single multi-line prompt + its marking answer.
// Layout (printed): title, passage text, blank line, instruction, then the
// three scaffolded questions a/b/c, each followed by a ruled writing line.
function renderPassage(p: Passage): RawProblem {
    const [q1, q2, q3] = p.questions;
    const prompt = [
        p.title,
        p.text,
        '',
        'Answer the questions in full sentences.',
        `a) ${q1.q}`,
        RULE,
        `b) ${q2.q}`,
        RULE,
        `c) ${q3.q}`,
        RULE
    ].join('\n');
    // Marking guidance, not a false single key: the inferential answer states
    // a text-supported sample and accepts any sensible alternative; the
    // evidence answer quotes the detail and accepts other accurate quotes.
    const answer = [
        `a) ${q1.a}`,
        `b) ${q2.a} (any sensible answer supported by the text is accepted)`,
        `c) ${q3.a} (other accurate quotes/details are accepted)`
    ].join('\n');
    return { prompt, answer };
}

// Generator: deal the year's passage bank without repeats (deck), collect
// distinct blocks via sampleUnique keyed on the printed prompt. The space is
// the bank size (6 per year) — long documents re-deal whole passages, which
// is by design for reading tasks (a fresh passage each time, never the same
// passage repeated above every question).
function generateComprehension(rng: Rng, caps: Caps, count: number): RawProblem[] {
    const level = Math.min(Math.max(caps.level, 3), 6) as 3 | 4 | 5 | 6;
    const deck = localDeck(rng, BANKS[level]);
    return sampleUnique(
        count,
        () => renderPassage(deck.take()),
        (p) => p.prompt
    );
}

// Local Fisher–Yates shuffle (plugin isolation: no cross-plugin imports).
function shuffleLocal<T>(rng: Rng, items: readonly T[]): T[] {
    const out = [...items];
    for (let i = out.length - 1; i > 0; i--) {
        const j = rng.int(0, i);
        [out[i], out[j]] = [out[j], out[i]];
    }
    return out;
}

// Local deck (same contract as the framework's createDeck, kept local so the
// plugin file stays self-contained per the plugin contract in types.ts).
function localDeck<T>(rng: Rng, pool: readonly T[]): { take: () => T } {
    let queue = shuffleLocal(rng, pool);
    return {
        take: () => {
            if (queue.length === 0) queue = shuffleLocal(rng, pool);
            return queue.pop() as T;
        }
    };
}

