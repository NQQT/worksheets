// Explicit year-level routing via caps.level (T5) — clamp defensively.
const BANKS: Record<3 | 4 | 5 | 6, readonly WritingTask[]> = { 3: TASKS_Y3, 4: TASKS_Y4, 5: TASKS_Y5, 6: TASKS_Y6 };

// Render one task as a single multi-line prompt (plan scaffold + ruled
// composition space) + its marking-guidance answer.
function renderTask(t: WritingTask): RawProblem {
    const planLines = t.plan.map((p, i) => `${i + 1}. ${p}${PLAN_RULE}`).join('\n');
    const composeLines = Array.from({ length: t.composeLines }, () => RULE).join('\n');
    const prompt = [
        t.title,
        t.brief,
        '',
        'Plan first.',
        planLines,
        '',
        'Now write.',
        composeLines
    ].join('\n');
    // Open-ended task: marking guidance, not a false single key.
    const answer = `Success criteria: ${t.criteria}\nSample ideas: ${t.ideas}`;
    return { prompt, answer };
}

// Generator: deal the year's task bank without repeats; long documents
// re-deal whole tasks (a fresh project each page — repeats by design).
function generateWriting(rng: Rng, caps: Caps, count: number): RawProblem[] {
    const level = Math.min(Math.max(caps.level, 3), 6) as 3 | 4 | 5 | 6;
    const deck = localDeck(rng, BANKS[level]);
    return sampleUnique(
        count,
        () => renderTask(deck.take()),
        (p) => p.prompt
    );
}

// Local Fisher–Yates shuffle (plugin isolation: no cross-plugin imports).
function shuffleLocal<T>(rng: Rng, items: readonly T[]): T[] {
    const out = [...items];
    for (let i = out.length - 1; i > 0; i--) {
        const j = rng.int(0, i);
        [out[i], out[j]] = [out[j], out[i]];
    }
    return out;
}

// Local deck (same contract as the framework's createDeck, kept local so the
// plugin file stays self-contained per the plugin contract in types.ts).
function localDeck<T>(rng: Rng, pool: readonly T[]): { take: () => T } {
    let queue = shuffleLocal(rng, pool);
    return {
        take: () => {
            if (queue.length === 0) queue = shuffleLocal(rng, pool);
            return queue.pop() as T;
        }
    };
}

// Per-year scope line — exposes the genre/structure progression.
const SCOPE_BY_LEVEL: Record<number, string> = {
    3: 'narrative, informative and persuasive paragraphs with a plan',
    4: 'text stages, linked ideas, tension and description',
    5: 'purpose-specific structures, connectives, dialogue and viewpoint',
    6: 'adapted structures — review, letter, technical and formal tone'
};

// The plugin's declarative spec (exported for its own tests). ONE extended
// writing project per A4 page — plan scaffold plus a full page of ruled
// composition space, the A4-safe budget for every year.
export const writingSpec: WorksheetSpec = {
    id: 'writing',
    label: 'Writing Projects',
    icon: '✎',
    perPage: 1,
    singleColumn: true,
    offered: (grade: GradeConfig) => grade.available.includes('writing'),
    scope: (grade: GradeConfig) => SCOPE_BY_LEVEL[grade.caps.level] ?? SCOPE_BY_LEVEL[3],
    generate: generateWriting
};

// The plugin: a function the dashboard calls with its framework bundle.
export function WritingWorksheet(dashboard: DashboardFramework): DashboardPlugin {
    return dashboard.createWorksheet(writingSpec);
}
