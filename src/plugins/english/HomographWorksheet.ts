export const homographSpec: WorksheetSpec = {
    id: 'homograph',
    label: 'Homographs',
    icon: '⚭',
    perPage: 8,
    offered: (grade: GradeConfig) => grade.available.includes('homograph'),
    scope: () => 'same spelling, new meaning',
    generate: generateHomograph
};

// The plugin: a function the dashboard calls with its framework bundle.
export function HomographWorksheet(dashboard: DashboardFramework): DashboardPlugin {
    return dashboard.createWorksheet(homographSpec);
}
