// Compound words — SIX procedural kinds (upper primary):
//   0. written: "join these two words" (spelling answer)
//   1. MC: which compound is made from the dealt pair (3 options, two fakes
//      assembled from other compounds' halves)
//   2. reverse: "which two words make up '<compound>'?" (written "a + b")
//   3. MC: which of the three IS a real compound word (the compound beside
//      two cross-join fakes that pass the real-word blocklist)
//   4. MC APPLY: which bank compound fits the curated sentence frame
//   5. open-ended COMPOSE: "write your own compound word" — the key models
//      one and accepts any real compound
//
// NON-REPEATING SAMPLING: items are dealt from a deck and every question
// passes through sampleUnique keyed on the printed prompt.
function generateCompound(rng: Rng, _caps: Caps, count: number): RawProblem[] {
    const itemDeck = localDeck(rng, COMPOUND_ITEMS);
    const sentenceDeck = localDeck(rng, COMPOUND_SENTENCES);
    // Fakes join only the TWO-WORD halves (never a whole compound), so they
    // read as plausible child errors ("sunball") rather than triple mush.
    const halves = COMPOUND_ITEMS.flatMap(([first, second]) => [first, second]);
    // A cross-join is a usable FAKE only when it is neither a bank compound
    // nor a real English word the halves happen to form (see blocklist).
    const isFake = (word: string) =>
        !COMPOUND_ITEMS.some(([, , c]) => c === word) && !REAL_WORDS_OUTSIDE_BANK.has(word);
    return sampleUnique(
        count,
        () => {
            const kind = rng.int(0, 5);
            if (kind === 4) {
                // APPLY: the one bank compound that fits the sentence.
                const [answer, sentence, distractors] = sentenceDeck.take();
                const shown = shuffleLocal(rng, [answer, ...distractors]);
                return { prompt: `Which compound word fits: ${sentence} (${shown.join(', ')})`, answer };
            }
            if (kind === 5) {
                // OPEN-ENDED compose: any real compound word is correct.
                const example = itemDeck.take()[2];
                return {
                    prompt: 'Write your own compound word (two words joined into one).',
                    answer: `Example: ${example} (any real compound word is correct)`
                };
            }
            const [first, second, compound] = itemDeck.take();
            if (kind === 0) {
                return { prompt: `Join into one word: ${first} + ${second}`, answer: compound };
            }
            if (kind === 1) {
                // MC: the compound beside two fake joins from other halves.
                // Only the dealt pair forms the answer, so real-word fakes
                // cannot make this question ambiguous — but the blocklist
                // keeps the fakes clearly non-words anyway.
                const options = [compound];
                let guard = 0;
                while (options.length < 3 && guard < 48) {
                    guard++;
                    const h1 = rng.pick(halves);
                    const h2 = rng.pick(halves);
                    const fake = `${h1}${h2}`;
                    if (isFake(fake) && !options.includes(fake) && fake !== compound) {
                        options.push(fake);
                    }
                }
                const shown = shuffleLocal(rng, options);
                return { prompt: `Which word is made from "${first}" and "${second}"? (${shown.join(', ')})`, answer: compound };
            }
            if (kind === 2) {
                return { prompt: `Which two words make up "${compound}"?`, answer: `${first} + ${second}` };
            }
            // MC: pick the real compound from three candidates. The fakes are
            // blocklist-filtered cross-joins, so exactly ONE option is a word.
            const fakes: string[] = [];
            let guard = 0;
            while (fakes.length < 2 && guard < 48) {
                guard++;
                const h1 = rng.pick(halves);
                const h2 = rng.pick(halves);
                const fake = `${h1}${h2}`;
                if (isFake(fake) && !fakes.includes(fake) && fake !== compound) {
                    fakes.push(fake);
                }
            }
            const shown = shuffleLocal(rng, [compound, ...fakes]);
            return { prompt: `Which one is a real compound word? (${shown.join(', ')})`, answer: compound };
        },
        (p) => p.prompt
    );
}

// Local Fisher–Yates shuffle (plugin isolation: no cross-plugin imports).
function shuffleLocal<T>(rng: Rng, items: readonly T[]): T[] {
    const out = [...items];
    for (let i = out.length - 1; i > 0; i--) {
        const j = rng.int(0, i);
        [out[i], out[j]] = [out[j], out[i]];
    }
    return out;
}

// Local deck (same contract as the framework's createDeck, kept local so the
// plugin file stays self-contained per the plugin contract in types.ts).
function localDeck<T>(rng: Rng, pool: readonly T[]): { take: () => T } {
    let queue = shuffleLocal(rng, pool);
    return {
        take: () => {
            if (queue.length === 0) queue = shuffleLocal(rng, pool);
            return queue.pop() as T;
        }
    };
}

