// Explicit year-level routing via caps.level (T5) — clamp defensively so an
// unexpected level can never crash the generator.
const BANKS: Record<3 | 4 | 5 | 6, CraftBank> = { 3: BANK_Y3, 4: BANK_Y4, 5: BANK_Y5, 6: BANK_Y6 };

// Generator — FIVE kinds per year, same slots every year so the PROGRESSION
// is the bank, not the task type (learn/support → practise/core → stretch):
//   0 REORDER/REWRITE (scaffolded production, deterministic or model)
//   1 EXPAND (core: add detail / widen / embed)
//   2 JOIN (core: combine with a named conjunction)
//   3 MC ANALYSE (practise: judge the best option)
//   4 COMPOSE (stretch: open-ended, example + acceptance note)
function generateCraft(rng: Rng, caps: Caps, count: number): RawProblem[] {
    const level = Math.min(Math.max(caps.level, 3), 6) as 3 | 4 | 5 | 6;
    const bank = BANKS[level];
    const expandDeck = localDeck(rng, bank.expand);
    const joinDeck = localDeck(rng, bank.join);
    const mcDeck = localDeck(rng, bank.mc);
    const rewriteDeck = localDeck(rng, bank.rewrite);
    return sampleUnique(
        count,
        () => {
            const kind = rng.int(0, 4);
            if (kind === 4) {
                // STRETCH compose: example + acceptance (no false single key).
                const c = rng.pick(bank.compose);
                return {
                    prompt: `${c.prompt}\n${RULE}`,
                    answer: `Example: ${c.example} (any sensible sentence meeting the task is correct)`
                };
            }
            if (kind === 3) {
                // MC analyse: options joined with " / " (sentence options
                // contain commas, so ", " would be ambiguous). When the item
                // carries a base sentence, it prints before the option list.
                const m = mcDeck.take();
                const shown = shuffleLocal(rng, m.options);
                const stem = m.base ? `${m.stem} "${m.base}"` : m.stem;
                return { prompt: `${stem} (${shown.join(' / ')})`, answer: m.answer };
            }
            if (kind === 2) {
                const [main, sub, conj, joined] = joinDeck.take();
                return {
                    prompt: `Join the two sentences with "${conj}" to make one sentence:\n"${main}."  "${sub}."\n${RULE}`,
                    answer: joined
                };
            }
            if (kind === 1) {
                const [base, detail, expanded, style] = expandDeck.take();
                if (style === 'instruction') {
                    // T9: the "detail" is a WRITING INSTRUCTION (Y5 expanded
                    // noun groups), not a literal phrase — the stem asks for a
                    // descriptive rewrite and the rubric accepts any sensible
                    // descriptive wording (a "placement" rubric would be
                    // nonsensical for an instruction).
                    return {
                        prompt: `Make the sentence more descriptive — add ${detail}:\n"${base}"\n${RULE}`,
                        answer: `Example: ${expanded} (any sensible descriptive wording that covers the instruction is correct)`
                    };
                }
                return {
                    prompt: `Add the detail "${detail}" to the sentence. Write your new sentence:\n"${base}"\n${RULE}`,
                    answer: `Example: ${expanded} (any sensible placement of "${detail}" is correct)`
                };
            }
            // kind 0 — scaffolded rewrite/reorder. Deterministic answers for
            // reorders/openers; tone rewrites already carry their
            // "Example: ... (any sensible ... is correct)" guidance in the
            // bank itself (open: true items).
            const r = rewriteDeck.take();
            return { prompt: `${r.instruction}\n${r.shown}\n${RULE}`, answer: r.answer };
        },
        (p) => p.prompt
    );
}

// Local Fisher–Yates shuffle (plugin isolation: no cross-plugin imports).
function shuffleLocal<T>(rng: Rng, items: readonly T[]): T[] {
    const out = [...items];
    for (let i = out.length - 1; i > 0; i--) {
        const j = rng.int(0, i);
        [out[i], out[j]] = [out[j], out[i]];
    }
    return out;
}

// Local deck (same contract as the framework's createDeck, kept local so the
// plugin file stays self-contained per the plugin contract in types.ts).
function localDeck<T>(rng: Rng, pool: readonly T[]): { take: () => T } {
    let queue = shuffleLocal(rng, pool);
    return {
        take: () => {
            if (queue.length === 0) queue = shuffleLocal(rng, pool);
            return queue.pop() as T;
        }
    };
}

// Per-year scope line — exposes the sentence-crafting focus of each level.
const SCOPE_BY_LEVEL: Record<number, string> = {
    3: 'reorder, add detail, join with and/but/or/so/because',
    4: 'combine with when/while/although, add adverbial detail',
    5: 'complex sentences — reason, purpose, condition, concession',
    6: 'embedded clauses, varied openers, formal and objective tone'
};

// The plugin's declarative spec (exported for its own tests). Prose rows —
// single column, 4 rows per A4 page (task + ruled writing line each). T12:
// 6 rows exceeded the printable grid budget on keyed Y4–Y6 pages. T15: the
// corrected capacity model (PER-LINE wrapping at 45 chars/line honouring
// forced '\n' breaks, +16px inter-row gaps, +4px answer-key margins) showed
// 5 rows still left only ~14px headroom on keyed Craft Y6 pages at realistic
// metrics and clipped under the conservative 45ch stress — 4 rows restores a
// safe margin in BOTH metrics (see print-capacity.test.ts worst-page pins).
export const craftSpec: WorksheetSpec = {
    id: 'craft',
    label: 'Crafting Sentences',
    icon: '⤴',
    perPage: 4,
    singleColumn: true,
    offered: (grade: GradeConfig) => grade.available.includes('craft'),
    scope: (grade: GradeConfig) => SCOPE_BY_LEVEL[grade.caps.level] ?? SCOPE_BY_LEVEL[3],
    generate: generateCraft
};

// The plugin: a function the dashboard calls with its framework bundle.
export function CraftWorksheet(dashboard: DashboardFramework): DashboardPlugin {
    return dashboard.createWorksheet(craftSpec);
}
