// A ruled WRITING line (see PrintableSheet PromptText: "__" tokens render as
// connected fill-in blanks on one baseline).
const RULE = '__ __ __ __ __ __ __ __ __ __';

// ── Item shapes (shared across the four year banks) ─────────────────────────
// EXPAND: [base sentence, detail to add, model expanded sentence, style?].
// Default style = the detail is a LITERAL PHRASE to place ("Add the detail
// \"loudly\"..."). T9: Year 5 details are WRITING INSTRUCTIONS ("which
// teacher and how they spoke") — those items carry style 'instruction' so
// the generator prints a descriptive-rewrite stem/rubric instead of the
// nonsensical "placement of <instruction>" rubric.
type ExpandItem = [string, string, string, 'instruction'?];
// JOIN: [main clause, subordinate clause, named conjunction, model joined].
type JoinItem = [string, string, string, string];
// MC: stem + optional base sentence + options + the one correct option
// (options joined with " / " so sentence-length options containing commas
// stay parseable).
type McItem = { stem: string; base?: string; options: string[]; answer: string };
// REWRITE: instruction + shown source + answer; `open` marks tone/production
// rewrites whose answer is a model (accept any sensible equivalent).
type RewriteItem = { instruction: string; shown: string; answer: string; open: boolean };
// COMPOSE: open-ended stretch task + example.
type ComposeItem = { prompt: string; example: string };

// One bank per year level (routed explicitly by caps.level below).
type CraftBank = {
    expand: readonly ExpandItem[];
    join: readonly JoinItem[];
    mc: readonly McItem[];
    rewrite: readonly RewriteItem[];
    compose: readonly ComposeItem[];
};

